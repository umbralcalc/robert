"""Render per-agent adapters from the one source of method content in skills/.

Method content has one source. These thin adapters only change its packaging: a
Claude Code plugin, Cursor rules plus MCP config, and an AGENTS.md for anything
else. Correctness never lives here; it lives in the MCP tools every adapter calls.
`tests/test_adapters.py` fails when a committed adapter drifts from its source.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

from . import __version__
from .scaffold import MCP_SERVER
from .tools import TOOLS

REPO = Path(__file__).resolve().parents[1]
AUTHOR = {"name": "umbralcalc", "email": "umbralcalc@gmail.com",
          "url": "https://github.com/umbralcalc/robert"}
DESCRIPTION = ("The AI simulation scientist: drives stochadex projects through the "
               "discovery-and-warrant loop, with every gate enforced by the robert MCP server.")
HEADER = "<!-- Generated by `robert adapters` from skills/. Do not edit by hand. -->\n"


def skills(repo: Path = REPO) -> list[tuple[dict[str, str], str]]:
    out = []
    for path in sorted((repo / "skills").glob("*/SKILL.md")):
        _, front, body = path.read_text().split("---", 2)
        # Strict YAML: the Skills API that `ant apply` uploads to parses it so too.
        out.append((yaml.safe_load(front), body.strip() + "\n"))
    return out


def _nest_headings(body: str) -> str:
    """Push a skill's headings two levels down, leaving code blocks alone."""
    lines, fenced = [], False
    for line in body.splitlines(keepends=True):
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced and re.match(r"#+ ", line):
            line = "##" + line
        lines.append(line)
    return "".join(lines)


def outputs(repo: Path = REPO) -> dict[str, str]:
    """Every adapter file, keyed by path relative to the repo."""
    files: dict[str, str] = {}
    files[".claude-plugin/plugin.json"] = json.dumps({
        "name": "robert",
        "description": DESCRIPTION,
        "version": __version__,
        "author": AUTHOR,
        "repository": AUTHOR["url"],
        "license": "MIT",
        "keywords": ["simulation", "stochadex", "scientific-method", "agent-skill"],
        "skills": "./skills/",
        "mcpServers": {"robert": MCP_SERVER},
    }, indent=2) + "\n"
    files[".claude-plugin/marketplace.json"] = json.dumps({
        "name": "robert",
        "owner": AUTHOR,
        "metadata": {"description": DESCRIPTION, "version": __version__},
        "plugins": [{"name": "robert", "source": ".", "description": DESCRIPTION,
                     "category": "modeling",
                     "keywords": ["simulation", "stochadex", "scientific-method"]}],
    }, indent=2) + "\n"
    files["adapters/cursor/mcp.json"] = json.dumps(
        {"mcpServers": {"robert": MCP_SERVER}}, indent=2) + "\n"

    agents = [HEADER, "# robert: the simulation scientist\n\n",
              "Connect the `robert` MCP server (`robert mcp`, stdio) and follow the "
              "skills below. The tools enforce the gates; these notes explain them.\n\n",
              "## Tools\n\n"]
    agents += [f"- `{t.name}`: {t.description}\n" for t in TOOLS]
    for front, body in skills(repo):
        files[f"adapters/cursor/rules/{front['name']}.mdc"] = (
            f"---\ndescription: {json.dumps(front['description'], ensure_ascii=False)}\n"
            "alwaysApply: false\n---\n"
            + HEADER + body)
        agents += [f"\n## Skill: {front['name']}\n\n", _nest_headings(body)]
    files["adapters/agents/AGENTS.md"] = "".join(agents)

    # The Managed Agents agent: its frontmatter stays as written in the file, and
    # its system prompt is the instructions every cloud runner gets.
    agent = repo / "cloud/agents/robert/agent.md"
    if agent.exists():
        _, front, _ = agent.read_text().split("---", 2)
        instructions = (REPO / "robert/cloud/instructions.md").read_text()
        files["cloud/agents/robert/agent.md"] = f"---{front}---\n\n{instructions}"
    return files


def render(repo: Path = REPO) -> list[str]:
    written = []
    for rel, text in outputs(repo).items():
        p = repo / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        written.append(rel)
    return written
